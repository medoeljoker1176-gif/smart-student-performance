"""
config.py
---------
One place for paths, feature lists, valid input ranges and the risk thresholds.
Every other module imports from here, so nothing is hard-coded twice.
"""
from pathlib import Path

# ------------------------------------------------------------------ paths
ROOT = Path(__file__).resolve().parent.parent
DATA_PATH = ROOT / "data" / "student_performance.csv"
HISTORY_PATH = ROOT / "data" / "prediction_history.csv"
MODEL_PATH = ROOT / "models" / "student_performance_model.pkl"
REPORT_DIR = ROOT / "reports"
METRICS_PATH = REPORT_DIR / "metrics.json"
OOF_PATH = REPORT_DIR / "oof_predictions.csv"   # out-of-fold predictions (fairness, risk tiers)

# --------------------------------------------------------------- dataset profiles
# The app can run on two datasets. Each has its own CSV, trained model and report folder, so
# switching never overwrites the other one. "synthetic" is the default and keeps the paths above.
DEFAULT_DATASET = "synthetic"
UCI_RAW_DIR = ROOT / "data" / "raw"                 # put student-mat.csv / student-por.csv here
DATASETS = {
    "synthetic": {
        "label": "Synthetic (generated)",
        "data": DATA_PATH, "model": MODEL_PATH, "reports": REPORT_DIR,
        "note": "Generated by generate_dataset.py with a fixed seed. Not real students.",
    },
    "uci": {
        "label": "UCI Student Performance (real)",
        "data": ROOT / "data" / "uci_student_performance.csv",
        "model": ROOT / "models" / "uci_student_performance_model.pkl",
        "reports": ROOT / "reports" / "uci",
        "note": ("Real records of Portuguese secondary-school students (UCI Machine Learning Repository, "
                 "CC BY 4.0). Sleep hours and class participation do not exist in that dataset, so the "
                 "model ignores them; Previous/Assignment score are the period-1/period-2 grades."),
    },
}


def dataset_paths(name: str = DEFAULT_DATASET) -> dict:
    """Paths for one dataset profile: data, model, reports, metrics, oof."""
    if name not in DATASETS:
        raise ValueError(f"Unknown dataset '{name}'. Choose one of: {', '.join(DATASETS)}")
    d = DATASETS[name]
    return {"data": d["data"], "model": d["model"], "reports": d["reports"],
            "metrics": d["reports"] / "metrics.json", "oof": d["reports"] / "oof_predictions.csv",
            "label": d["label"], "note": d["note"]}


